export function profileFor(value: string) {
  return HELP_PROFILES.find((profile) => profile.match.test(value)) || FALLBACK_PROFILE;
}

export function roleFor(user: HelpUser | null) {
  const role = user?.role || user?.roles?.[0];
  return role ? ROLE_LABELS[role.toUpperCase()] || role : "Роль не определена";
}
